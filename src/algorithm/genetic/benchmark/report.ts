import type { Metrics, ProblemResult } from "./types";

function fmt(x: number | null): string {
  if (x === null) return "-";
  if (Number.isInteger(x)) return String(x);
  return x.toFixed(4);
}

export function renderMarkdown(
  metrics: Metrics,
  results: ProblemResult[],
  configHeader: string,
): string {
  const lines: string[] = [];

  lines.push("# Benchmark Report — GA vs UCS on the Sandbox Puzzle");
  lines.push("");
  lines.push("> Generated by `npm run benchmark`. Fully reproducible: the same");
  lines.push("> `baseSeed` regenerates byte-identical `benchmark-results.json`.");
  lines.push("");
  lines.push("## Configuration");
  lines.push("");
  lines.push("```");
  lines.push(configHeader);
  lines.push("```");
  lines.push("");

  lines.push("## Required indicators");
  lines.push("");
  lines.push("| # | Indicator | Value |");
  lines.push("|---|---|---|");
  lines.push(`| 1 | GA successes (goal reached) | ${metrics.gaSuccesses} / ${metrics.totalProblems} (${metrics.gaSuccessRatePercent.toFixed(1)}%) |`);
  lines.push(`| 2 | GA successes with optimal path_cost | ${metrics.gaSuccessWithOptimum} / ${metrics.gaSuccesses} = ${metrics.gaSuccessWithOptimumPercentOfGaSuccess.toFixed(1)}% of GA successes; ${metrics.gaSuccessWithOptimumPercentOfAll.toFixed(1)}% of all problems |`);
  lines.push(`| 3 | Mean GA/UCS ratio over all measurable problems | ${fmt(metrics.meanRatioOverMeasurable)} (N = ${metrics.measurableCount} / ${metrics.totalProblems}) |`);
  lines.push(`| 4 | Mean GA/UCS ratio over GA-solved problems | ${fmt(metrics.meanRatioOverGaSolved)} (N = ${metrics.gaSolvedWithOptimumCount}) |`);
  lines.push("");
  lines.push("> Note on indicators 3 and 4: both are restricted to problems where **both** algorithms");
  lines.push("> found a solution, so they coincide numerically. The N is reported explicitly. If you");
  lines.push("> prefer a penalized interpretation for indicator 3 (count GA failures as worst-case),");
  lines.push("> set `metrics.gaFailures` as a separate figure: it is already listed below.");
  lines.push("");

  lines.push("## Extended statistics");
  lines.push("");
  lines.push(`- Median ratio: ${fmt(metrics.medianRatioOverMeasurable)}`);
  lines.push(`- Min ratio: ${fmt(metrics.minRatio)}`);
  lines.push(`- Max ratio: ${fmt(metrics.maxRatio)}`);
  lines.push(`- GA failures (no goal): ${metrics.gaFailures}`);
  lines.push(`- UCS failures (no goal): ${metrics.ucsFailures}`);
  lines.push(`- Both failed: ${metrics.bothFailed}`);
  lines.push(`- GA avg time: ${metrics.gaAvgMs.toFixed(1)} ms / problem`);
  lines.push(`- UCS avg time: ${metrics.ucsAvgMs.toFixed(1)} ms / problem`);
  lines.push(`- Total GA time: ${metrics.totalGaMs.toFixed(0)} ms`);
  lines.push(`- Total UCS time: ${metrics.totalUcsMs.toFixed(0)} ms`);
  lines.push("");

  lines.push("## Ratio distribution");
  lines.push("");
  lines.push("| Bucket | Count |");
  lines.push("|---|---|");
  lines.push(`| exactly equal (ratio = 1.0) | ${metrics.ratioBuckets.equal} |`);
  lines.push(`| 1.0 < ratio <= 1.10 | ${metrics.ratioBuckets.upTo110} |`);
  lines.push(`| 1.10 < ratio <= 1.25 | ${metrics.ratioBuckets.upTo125} |`);
  lines.push(`| 1.25 < ratio <= 1.50 | ${metrics.ratioBuckets.upTo150} |`);
  lines.push(`| 1.50 < ratio <= 2.00 | ${metrics.ratioBuckets.upTo200} |`);
  lines.push(`| ratio > 2.00 | ${metrics.ratioBuckets.over200} |`);
  lines.push("");

  lines.push("## Per-problem results");
  lines.push("");
  lines.push("| # | seed | GA found | GA cost | GA steps | UCS cost | UCS exp | ratio | status |");
  lines.push("|---|---|---|---|---|---|---|---|---|");
  for (const r of results) {
    lines.push(
      `| ${r.index} | ${r.seed} | ${r.gaFound ? "Y" : "N"} | ${fmt(r.gaCost)} | ${r.gaPathLength || "-"} | ${fmt(r.ucsCost)} | ${r.ucsExpanded} | ${fmt(r.ratio)} | ${r.ratioStatus} |`,
    );
  }
  lines.push("");

  const gaFailures = results.filter((r) => !r.gaFound);
  if (gaFailures.length > 0) {
    lines.push("## GA failure cases");
    lines.push("");
    lines.push("| # | seed | UCS found | UCS cost | UCS expanded |");
    lines.push("|---|---|---|---|---|");
    for (const r of gaFailures) {
      lines.push(`| ${r.index} | ${r.seed} | ${r.ucsFound ? "Y" : "N"} | ${fmt(r.ucsCost)} | ${r.ucsExpanded} |`);
    }
    lines.push("");
  }

  const suboptimal = results.filter((r) => r.ratio !== null && r.ratio > 1);
  if (suboptimal.length > 0) {
    lines.push("## Suboptimal GA solutions");
    lines.push("");
    lines.push("| # | seed | GA cost | UCS cost | ratio | GA steps |");
    lines.push("|---|---|---|---|---|---|");
    for (const r of suboptimal) {
      lines.push(`| ${r.index} | ${r.seed} | ${fmt(r.gaCost)} | ${fmt(r.ucsCost)} | ${fmt(r.ratio)} | ${r.gaPathLength} |`);
    }
    lines.push("");
  }

  lines.push("## Notes");
  lines.push("");
  lines.push("- `ratio = GA_cost / UCS_cost`. A ratio of 1.0 means the GA found an optimal solution.");
  lines.push("- The GA models the world using pure `applyGate` transitions (no shelf state, no cascading).");
  lines.push("  The UCS baseline (`planning/solver.ts::solve`) uses the same model — both ignore shelf state,");
  lines.push("  so the comparison is fair.");
  lines.push("- Problems where either algorithm failed are excluded from ratio statistics but counted in");
  lines.push("  success rates and in the failure counts.");
  lines.push("");

  return lines.join("\n");
}
